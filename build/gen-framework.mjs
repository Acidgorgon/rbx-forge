// Regenerates src/main/agent/framework/content.ts from FRAMEWORK.md and SKILL.md next to it.
// Run after editing either file: npm run gen:framework (test/frameworkPlaybook.test.ts checks they match).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'main', 'agent', 'framework')
const read = (name) => readFileSync(join(dir, name), 'utf8').replace(/\r\n/g, '\n').trim()
const lit = (text) => '`' + text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`'

const out = `// Generated by build/gen-framework.mjs from FRAMEWORK.md and SKILL.md. Edit those, then run npm run gen:framework.

export const FRAMEWORK_PLAYBOOK = ${lit(read('FRAMEWORK.md'))}

export const REFACTOR_SKILL = ${lit(read('SKILL.md'))}
`
writeFileSync(join(dir, 'content.ts'), out, 'utf8')
console.log('wrote src/main/agent/framework/content.ts')
