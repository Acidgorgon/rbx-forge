// Project map (budget/projectMap.ts) on the GenTree fixture.

import { test } from 'node:test'
import assert from 'node:assert/strict'
import type { ScriptGroup } from '../src/shared/types.ts'
import { parseLuau, ProjectMap, resolveScriptRequire, shortenRequire } from '../src/main/agent/budget/projectMap.ts'
import { estimateTokens } from '../src/main/agent/budget/tokens.ts'
import { fixtureFs, fixtureScripts, fixtureStat } from './tokensFixture.ts'

async function makeMap(overrides: Record<string, string> = {}, withStat = false) {
  const fs = fixtureFs(undefined, overrides)
  const groups = await fixtureScripts()
  const map = new ProjectMap({ scripts: () => groups, readFile: fs.readFile, ...(withStat ? { stat: fixtureStat } : {}) })
  return { map, fs, groups }
}

test('shortenRequire strips services and WaitForChild', () => {
  assert.equal(shortenRequire('ReplicatedStorage.Packages.Janitor'), 'Packages.Janitor')
  assert.equal(shortenRequire('game:GetService("ReplicatedStorage").Shared.Util'), 'Shared.Util')
  assert.equal(shortenRequire('game.ServerScriptService.Server:WaitForChild("Data")'), 'Server.Data')
  assert.equal(shortenRequire('Shared["Feature Flags"]'), 'Shared.Feature Flags')
  assert.equal(shortenRequire('"@pkg/janitor"'), '@pkg/janitor')
})

test('resolveScriptRequire maps script.Parent chains to repo paths', () => {
  assert.equal(resolveScriptRequire('src/server/Features/Inventory/InventoryService.luau', 'script.Parent.Parent.Parent.Data.PlayerData'), 'server/Data/PlayerData')
  assert.equal(resolveScriptRequire('src/server/Features/Inventory/init.server.luau', 'script.InventoryService'), 'server/Features/Inventory/InventoryService')
  assert.equal(resolveScriptRequire('src/a.luau', 'script.Parent.Parent.Parent.X'), 'script.Parent.Parent.Parent.X')
  assert.equal(resolveScriptRequire('src/a.luau', 'Packages.X'), 'Packages.X')
})

test('parseLuau: exports, methods, fields, top-level requires only', () => {
  const p = parseLuau(
    [
      'local RS = game:GetService("ReplicatedStorage")',
      'local Janitor = require(RS.Packages.Janitor)',
      'local M = {}',
      'M.Count = 0',
      'M.Get = function() end',
      'local function helper() end',
      'function M.Add(a) end',
      'function M:Init()',
      '\tlocal Lazy = require(script.Lazy)',
      'end',
      'function Other.Nope() end',
      '--[[',
      'function M:Commented() end',
      ']]',
      'return M'
    ].join('\n')
  )
  assert.deepEqual(p.requires, ['RS.Packages.Janitor'])
  assert.equal(p.returns, 'M')
  assert.equal(p.returnsFunction, false)
  assert.deepEqual(
    p.exports.map((e) => [e.name, e.kind, e.line]),
    [
      ['Count', 'field', 4],
      ['Get', 'function', 5],
      ['Add', 'function', 7],
      ['Init', 'method', 8]
    ]
  )
  assert.equal(p.lines, 15)
})

test('parseLuau: function modules and Blink outputs', () => {
  assert.equal(parseLuau('local function app() end\n\nreturn app\n').returnsFunction, true)
  assert.equal(parseLuau('return function() end\n').returnsFunction, true)
  const blink = parseLuau('--!strict\n-- File generated by Blink v0.18.1 (https://github.com/1Axen/Blink)\nlocal function Read() end\nreturn {}\n')
  assert.equal(blink.generated, 'blink')
  assert.deepEqual(blink.exports, [])
})

test('map of the fixture: one line per script with categories, requires, exports, lifecycle', async () => {
  const { map } = await makeMap()
  const r1 = await map.refresh()
  assert.equal(r1.changed.length, 12)
  assert.equal(r1.version, 1)
  const { text, tokens, level, scripts } = map.render()
  assert.equal(level, 0)
  assert.equal(scripts, 12)
  assert.equal(tokens, estimateTokens(text))
  assert.ok(tokens < 600, `fixture map should be small, got ${tokens}`)
  // Packages are never in the map.
  assert.ok(!text.includes('Packages/Janitor'))
  assert.match(text, /InventoryService\.luau svc 38L req=Packages\.Janitor,Shared\.Features\.Inventory,Server\.events\.server,server\/Data\/PlayerData exp=Inventories,:Init\(\),:Start\(\),AddItem\(\),:GetItems\(\) lc=Init\+Start/)
  // ShopController has Start only inside a block comment.
  assert.match(text, /ShopController\/ \(client\)\n {2}init\.luau ctl 19L req=Packages\.Vide exp=:Init\(\),:Toggle\(\) lc=Init\n/)
  assert.match(text, /ModuleLoader\.luau mod 86L req=Packages\.Janitor exp=Janitors,Modules,ClientLoaded,InitFolder\(\)/)
  assert.match(text, /app\.luau ui 14L req=Packages\.Vide exp=\(function\)/)
  assert.match(text, /client\.luau evt \d+L generated by Blink/)
  assert.match(text, /init\.luau cfg 7L exp=MaxSlots,StackSize/)
})

test('render is memoized and byte-stable until something changes', async () => {
  const { map } = await makeMap()
  await map.refresh()
  const a = map.render()
  const b = map.render()
  assert.equal(a, b)
  const r2 = await map.refresh()
  assert.deepEqual(r2.changed, [])
  assert.equal(r2.version, 1)
  assert.equal(map.render(), a)
})

test('incremental refresh: hash mode re-parses only changed content', async () => {
  const overrides: Record<string, string> = {}
  const { map } = await makeMap(overrides)
  await map.refresh()
  overrides['src/server/Data/PlayerData.luau'] = 'local PlayerData = {}\nfunction PlayerData.Save() end\nreturn PlayerData\n'
  const r = await map.refresh()
  assert.deepEqual(r.changed, ['src/server/Data/PlayerData.luau'])
  assert.equal(r.version, 2)
  assert.match(map.render().text, /PlayerData\.luau data 3L exp=Save\(\)/)
})

test('incremental refresh: stat mode skips reading unchanged files', async () => {
  const { map, fs } = await makeMap({}, true)
  await map.refresh()
  const firstReads = fs.reads.length
  assert.equal(firstReads, 12)
  await map.refresh()
  assert.equal(fs.reads.length, firstReads, 'no file re-read when stat is unchanged')
})

test('removed scripts disappear', async () => {
  const { map, groups } = await makeMap()
  await map.refresh()
  const fewer: ScriptGroup[] = groups.map((g) => ({ ...g, scripts: g.scripts.filter((s) => !s.path.includes('ShopController')) }))
  const map2 = map as unknown as { src: { scripts: () => ScriptGroup[] } }
  map2.src.scripts = () => fewer
  const r = await map.refresh()
  assert.deepEqual(r.removed, ['src/client/Client/Controllers/ShopController/init.luau'])
  assert.ok(!map.render().text.includes('ShopController'))
})

test('filters: path prefix, realm, category', async () => {
  const { map } = await makeMap()
  await map.refresh()
  const server = map.render({ realm: 'server' }).text
  assert.ok(server.includes('InventoryService') && !server.includes('ModuleLoader'))
  const feat = map.render({ path: 'src/server/Features/' })
  assert.equal(feat.scripts, 2)
  assert.equal(map.render({ category: 'svc' }).scripts, 1)
  assert.equal(map.render({ category: 'Controllers' }).scripts, 2)
  assert.equal(map.render({ path: 'nope' }).text, '(no scripts match)')
})

test('over budget: degrades through levels, then collapses folders, always within budget', async () => {
  const { map } = await makeMap()
  await map.refresh()
  const full = map.render().tokens
  let prevLevel = 0
  for (const budget of [full, Math.floor(full * 0.8), Math.floor(full * 0.6), 200, 120]) {
    const r = map.render({ maxTokens: budget })
    assert.ok(r.tokens <= budget, `budget ${budget}: got ${r.tokens} at level ${r.level}`)
    assert.ok(r.level >= prevLevel, 'levels never go back up as the budget shrinks')
    prevLevel = r.level
  }
  const tiny = map.render({ maxTokens: 120 })
  assert.equal(tiny.level, 4)
  assert.match(tiny.text, /collapsed: \d+ scripts/)
  assert.match(tiny.text, /call project_map with path=/)
})

test('findSymbol: exact before partial, methods and modules', async () => {
  const { map } = await makeMap()
  await map.refresh()
  const add = map.findSymbol('AddItem')
  assert.deepEqual(add[0], { path: 'src/server/Features/Inventory/InventoryService.luau', line: 24, kind: 'function', name: 'InventoryService.AddItem' })
  const init = map.findSymbol('init')
  assert.ok(init.length >= 3)
  assert.ok(init.slice(0, 3).every((h) => h.kind === 'method' && h.name.endsWith(':Init')))
  assert.equal(map.findSymbol('InventoryService:GetItems')[0].line, 34)
  assert.equal(map.findSymbol('ShopController')[0].kind, 'module')
  assert.deepEqual(map.findSymbol('zzz'), [])
})
