// Delete flows the Explorer shares between the Game, Files and Features views: Delete in Studio (a
// Studio-only instance, through the Forge Bridge; Ctrl+Z in Studio restores it), Delete Feature (all
// of a feature's parts to the Recycle Bin / Trash) and the multi-select batches of both. Each asks
// first unless "Don't ask again" was ticked, and always when open tabs under it have unsaved changes.
import type { Actions, State } from '../store'
import { errorText } from '../lib/format'
import { featureDeleteTargets, findNode, type FeatureInfo } from '../lib/roblox'
import { shouldConfirmDelete } from '../lib/deleteConfirm'
import { isUnder } from '@shared/fileOps'
import { nameList, unselectedNote, type DeletePlan } from '@shared/explorerSelection'
import type { TreeNode } from '@shared/types'

export const trashName = (): string => (navigator.userAgent.includes('Windows') ? 'Recycle Bin' : 'Trash')

function descendants(node: TreeNode | null): number {
  if (!node) return 0
  return node.children.reduce((n, c) => n + 1 + descendants(c), 0)
}

export async function deleteInStudio(state: State, actions: Actions, instancePath: string[], className: string): Promise<void> {
  const dotted = instancePath.join('.')
  const name = instancePath[instancePath.length - 1]
  const check = await window.harness.syncDeleteCheck(instancePath).catch((e) => ({ reason: errorText(e) }))
  if ('reason' in check) {
    actions.toast({ text: `Cannot delete ${name} in Studio`, detail: check.reason, kind: 'err' })
    return
  }
  const run = () =>
    void window.harness
      .syncDeleteInStudio(instancePath, className)
      .then(() => actions.toast({ text: `Deleted ${name} in Studio`, detail: 'Ctrl+Z in Studio brings it back', kind: 'ok', ms: 4000 }))
      .catch((e) => actions.toast({ text: `Could not delete ${name} in Studio`, detail: errorText(e), kind: 'err' }))
  if (!shouldConfirmDelete(state.appSettings?.confirmStudioDelete, 0)) return run()
  const n = descendants(findNode(state.tree, instancePath))
  actions.openDialog({
    kind: 'confirm',
    title: `Delete ${name} in Studio?`,
    body: `Deletes ${dotted} (${className}${n ? `, and the ${n} instance${n === 1 ? '' : 's'} inside it` : ''}) from the place open in Studio. It is not in the repo, so Forge keeps no copy; Ctrl+Z in Studio brings it back.`,
    confirm: 'Delete in Studio',
    danger: true,
    dontAsk: 'confirmStudioDelete',
    run
  })
}

export function deleteFeature(state: State, actions: Actions, feature: FeatureInfo): void {
  const targets = featureDeleteTargets(feature)
  if (!targets.length) return
  const bin = trashName()
  const unsaved = state.files.filter((f) => f.current !== f.saved && targets.some((t) => (t.isDir ? isUnder(f.path, t.path) : f.path === t.path))).length
  const run = async () => {
    const failed: string[] = []
    // One at a time, in order (Controller, Service, shared last; see featureDeleteTargets).
    for (const t of targets) {
      try {
        await actions.trashPath(t.path, t.isDir)
      } catch (e) {
        failed.push(`${t.path}: ${errorText(e)}`)
      }
    }
    if (failed.length) actions.toast({ text: `Could not delete all of ${feature.name}`, detail: failed.join('\n'), kind: 'err' })
    else actions.toast({ text: `Deleted feature ${feature.name}`, detail: `${targets.length} item${targets.length === 1 ? '' : 's'} moved to the ${bin}`, kind: 'ok', ms: 3500 })
  }
  if (!shouldConfirmDelete(state.appSettings?.confirmFileDelete, unsaved)) return void run()
  actions.openDialog({
    kind: 'confirm',
    title: `Delete feature ${feature.name}?`,
    body: `Moves ${targets.length === 3 ? 'all three parts' : targets.length === 1 ? 'its only part' : `its ${targets.length} parts`} to the ${bin}; you can restore them from there.${unsaved ? ` ${unsaved === 1 ? 'An open file has' : `${unsaved} open files have`} unsaved changes that will be lost.` : ''}`,
    list: targets.map((t) => (t.isDir ? `${t.path}/` : t.path)),
    confirm: `Move to ${bin}`,
    danger: true,
    dontAsk: 'confirmFileDelete',
    run: () => void run()
  })
}

// ---- multi-select batches (Game and Files views)

const plural = (n: number, one: string, many = `${one}s`) => `${n} ${n === 1 ? one : many}`
const itThem = (n: number) => (n === 1 ? 'it' : 'them')

// The rows a batch leaves alone, grouped by why: "Packages (Wally package, read-only); Net (generated by Blink)".
function skippedList(skipped: DeletePlan['skipped']): string {
  const groups = new Map<string, string[]>()
  for (const s of skipped) groups.set(s.reason, [...(groups.get(s.reason) ?? []), s.name])
  return [...groups].map(([why, names]) => `${nameList(names)} (${why})`).join('; ')
}

// For a confirmation (nothing has run yet) and for the result toast.
const leavesOut = (skipped: DeletePlan['skipped']) => (skipped.length ? `Leaves out ${plural(skipped.length, 'item')} that cannot be deleted here: ${skippedList(skipped)}.` : '')
const leftAlone = (skipped: DeletePlan['skipped']) => (skipped.length ? `Left ${plural(skipped.length, 'item')} alone: ${skippedList(skipped)}.` : '')

// The selection's files and folders to the Recycle Bin / Trash, behind one confirmation listing
// them, as one batch in main (one Rojo pause, one tree refresh). Studio-only rows in the same
// selection are left for "Delete N in Studio". `hidden`: per folder in the batch, the files inside it
// that were not selected (shared/explorerSelection.ts unselectedInside); with any, the batch always
// asks, "Don't ask again" or not.
export function deleteManyFromDisk(state: State, actions: Actions, plan: DeletePlan, hidden: readonly { path: string; count: number }[] = []): void {
  const items = plan.disk
  const k = plan.studio.length
  const studioLeft = k ? `${plural(k, 'Studio-only instance')} ${k === 1 ? 'stays' : 'stay'}; use Delete in Studio for ${itThem(k)}.` : ''
  if (!items.length) {
    const none = plan.skipped.length ? `${plan.skipped.length === 1 ? 'It cannot' : 'None of these can'} be deleted here: ${skippedList(plan.skipped)}.` : ''
    actions.toast({ text: 'Nothing to delete', detail: [none, studioLeft].filter(Boolean).join(' ') || undefined, kind: 'info' })
    return
  }
  const bin = trashName()
  const n = items.length
  const what = plural(n, 'item')
  const unsaved = state.files.filter((f) => f.current !== f.saved && items.some((t) => isUnder(f.path, t.path))).length
  const run = async () => {
    try {
      const r = await actions.trashPaths(items.map(({ path, isDir }) => ({ path, isDir })))
      if (r.failed.length) {
        actions.toast({ text: `Deleted ${r.changes.length} of ${n}`, detail: r.failed.map((f) => `${f.path}: ${f.error}`).join('\n'), kind: 'err' })
      } else {
        const detail = [`Moved to the ${bin}.`, leftAlone(plan.skipped), studioLeft].filter(Boolean).join(' ')
        actions.toast({ text: `Deleted ${what}`, detail, kind: 'ok', ms: plan.skipped.length || k ? 6000 : 3500 })
      }
    } catch (e) {
      actions.toast({ text: `Could not delete ${what}`, detail: errorText(e), kind: 'err' })
    }
  }
  const setting = state.appSettings?.confirmFileDelete
  if (!hidden.length && !shouldConfirmDelete(setting, unsaved)) return void run()
  const folders = items.some((t) => t.isDir)
  const covered = plan.covered
  actions.openDialog({
    kind: 'confirm',
    title: `Delete ${what}?`,
    body: [
      n === 1
        ? `Moves ${items[0].isDir ? 'this folder and everything in it' : 'it'} to the ${bin}; you can restore it from there.`
        : `Moves these ${n} to the ${bin}${folders ? ' (folders with everything in them)' : ''}; you can restore them from there.`,
      covered ? `${plural(covered, 'selected item')} inside ${itThem(n)} ${covered === 1 ? 'goes' : 'go'} along.` : '',
      unselectedNote(hidden),
      unsaved ? `${unsaved === 1 ? 'An open file has' : `${unsaved} open files have`} unsaved changes that will be lost.` : '',
      leavesOut(plan.skipped),
      studioLeft
    ]
      .filter(Boolean)
      .join(' '),
    list: items.map((t) => (t.isDir ? `${t.path}/` : t.path)),
    confirm: `Move to ${bin}`,
    danger: true,
    // Asked although "Don't ask again" is ticked (unselected files in a folder, unsaved tabs): no box.
    dontAsk: setting === false ? undefined : 'confirmFileDelete',
    run: () => void run()
  })
}

// Which of the selection's Studio-only instances Forge can delete now (the same check as the single
// "Delete in Studio"); the rest join the skipped list with the reason.
export async function studioDeletable(plan: DeletePlan): Promise<{ ok: DeletePlan['studio']; refused: DeletePlan['skipped'] }> {
  const checks = await Promise.all(plan.studio.map((it) => window.harness.syncDeleteCheck(it.instancePath).catch((e) => ({ reason: errorText(e) }))))
  const ok: DeletePlan['studio'] = []
  const refused: DeletePlan['skipped'] = []
  plan.studio.forEach((it, i) => {
    const c = checks[i]
    if ('ok' in c) ok.push(it)
    else refused.push({ key: it.key, name: it.name, reason: c.reason })
  })
  return { ok, refused }
}

// "Delete N in Studio": the selection's Studio-only instances through the Forge Bridge, one job after
// another in main, behind one confirmation (Ctrl+Z in Studio brings each back).
export async function deleteManyInStudio(state: State, actions: Actions, plan: DeletePlan): Promise<void> {
  if (!plan.studio.length) return
  const { ok, refused } = await studioDeletable(plan)
  if (!ok.length) {
    actions.toast({ text: `Cannot delete ${plural(plan.studio.length, 'instance')} in Studio`, detail: refused[0]?.reason, kind: 'err' })
    return
  }
  const n = ok.length
  const skipped = [...plan.skipped, ...refused]
  const d = plan.disk.length
  const diskLeft = d ? `${plural(d, 'repo file or folder', 'repo files and folders')} ${d === 1 ? 'stays' : 'stay'}; use Delete for ${itThem(d)}.` : ''
  const run = () =>
    void window.harness
      .syncDeleteManyInStudio(ok.map((it) => ({ instancePath: it.instancePath, className: it.className })))
      .then((r) => {
        if (r.failed.length) actions.toast({ text: `Deleted ${r.deleted.length} of ${n} in Studio`, detail: r.failed.map((f) => `${f.instancePath.join('.')}: ${f.error}`).join('\n'), kind: 'err' })
        else actions.toast({ text: `Deleted ${plural(n, 'instance')} in Studio`, detail: [`Ctrl+Z in Studio brings ${itThem(n)} back.`, leftAlone(skipped), diskLeft].filter(Boolean).join(' '), kind: 'ok', ms: skipped.length || d ? 6000 : 4000 })
      })
      .catch((e) => actions.toast({ text: `Could not delete ${plural(n, 'instance')} in Studio`, detail: errorText(e), kind: 'err' }))
  if (!shouldConfirmDelete(state.appSettings?.confirmStudioDelete, 0)) return run()
  const inside = ok.reduce((sum, it) => sum + descendants(findNode(state.tree, it.instancePath)), 0)
  actions.openDialog({
    kind: 'confirm',
    title: `Delete ${plural(n, 'instance')} in Studio?`,
    body: [
      `Deletes ${n === 1 ? 'it' : `these ${n}`}${inside ? ` (and the ${plural(inside, 'instance')} inside ${itThem(n)})` : ''} from the place open in Studio. ${n === 1 ? 'It is' : 'They are'} not in the repo, so Forge keeps no copy; Ctrl+Z in Studio brings ${itThem(n)} back.`,
      leavesOut(skipped),
      diskLeft
    ]
      .filter(Boolean)
      .join(' '),
    list: ok.map((it) => it.instancePath.join('.')),
    confirm: 'Delete in Studio',
    danger: true,
    dontAsk: 'confirmStudioDelete',
    run
  })
}
