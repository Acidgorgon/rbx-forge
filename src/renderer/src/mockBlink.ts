const FIELD_VALUES: Record<string, string[]> = {
  From: ['Client', 'Server'],
  Type: ['Reliable', 'Unreliable'],
  Call: ['SingleSync', 'SingleAsync', 'ManySync', 'ManyAsync', 'Polling'],
  Yield: ['Future', 'Promise', 'Coroutine']
}

// Stand-in for the compile check: Blink's E2003 for unknown field values, worded as Blink 0.18.1 words it.
function mockDiagnostics(source: string): BlinkDiagnostic[] {
  const out: BlinkDiagnostic[] = []
  source.split('\n').forEach((text, k) => {
    const m = /^(\s*)(From|Type|Call|Yield)(\s*:\s*)([A-Za-z_]\w*)/.exec(text)
    if (!m || FIELD_VALUES[m[2]].includes(m[4])) return
    const column = m[1].length + m[2].length + m[3].length + 1
    out.push({
      file: 'events.blink',
      line: k + 1,
      column,
      endColumn: column + m[4].length,
      code: 'E2003',
      message: `Unknown option "${m[4]}"`,
      detail: `Expected one of "${FIELD_VALUES[m[2]].join('" or "')}"`,
      severity: 'error'
    })
  })
  return out.slice(0, 1) // Blink stops at the first error
}

export function mockBlinkModel(source: string): BlinkModel {
  const parsed = parseBlink(source, 'events.blink')
  return {
    file: 'events.blink',
    events: parsed.events,
    types: parsed.types,
    options: parsed.options,
    optionLines: parsed.optionLines,
    imports: [],
    outputs: BLINK_OUTPUTS,
    requirePaths: { client: 'ReplicatedStorage.Shared.events.client', server: 'ServerScriptService.Server.events.server' },
    diagnostics: mockDiagnostics(source),
    checker: 'blink',
    checkerDetail: 'blink 0.18.1',
    blinkVersion: '0.18.1',
    checkedAt: Date.now()
  }
}
