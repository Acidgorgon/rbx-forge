// Records the built-in Animation Lab examples (src/shared/anim/examples.ts) with Lune and writes
// src/shared/anim/examples.recorded.ts, so the examples load without Lune.
//   node --experimental-strip-types build/anim-examples.ts [path/to/lune]
import { writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { ANIM_EXAMPLES } from '../src/shared/anim/examples.ts'
import { findLune } from '../src/main/services/tests/lune.ts'
import { luneAnimTimeline } from '../src/main/services/anim/lune.ts'

const root = resolve(import.meta.dirname, '..')
const lune = process.argv[2] ?? process.env.LUNE ?? findLune()
if (!lune) {
  console.error('lune not found: pass its path or set LUNE')
  process.exit(1)
}
const out: Record<string, unknown> = {}
for (const ex of ANIM_EXAMPLES) {
  const rec = await luneAnimTimeline(ex.script, { lune, runtimeDir: join(root, 'resources', 'lune') })
  if (!rec.ok) {
    console.error(`${ex.key}: ${rec.error?.line ? `line ${rec.error.line}: ` : ''}${rec.error?.message}`)
    process.exit(1)
  }
  out[ex.key] = rec.ops
  console.log(`${ex.key}: ${rec.ops.length} ops`)
}
const file = join(root, 'src', 'shared', 'anim', 'examples.recorded.ts')
writeFileSync(
  file,
  `// Generated by build/anim-examples.ts from the scripts in examples.ts (Lune's recorder output). Do not edit.\nimport type { AnimOp } from './compile.ts'\n\nexport const ANIM_RECORDED: Record<string, AnimOp[]> = ${JSON.stringify(out)}\n`,
  'utf8'
)
console.log(`wrote ${file}`)
